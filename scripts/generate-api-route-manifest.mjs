import { mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const routesDir = path.join(repoRoot, "artifacts", "api-server", "src", "routes");
const outputPath = path.join(
  repoRoot,
  "artifacts",
  "api-server",
  "src",
  "generated",
  "api-route-manifest.ts",
);
const routePattern =
  /router\.(get|post|put|patch|delete|options|head|all)\s*\(\s*(["'])([^"']+)\2/gi;

function compareCodeUnits(left, right) {
  if (left < right) return -1;
  if (left > right) return 1;
  return 0;
}

const routes = [];
for (const fileName of readdirSync(routesDir).filter((name) => name.endsWith(".ts")).sort()) {
  if (fileName === "index.ts") continue;
  const source = readFileSync(path.join(routesDir, fileName), "utf8");
  for (const match of source.matchAll(routePattern)) {
    routes.push({
      method: match[1].toUpperCase(),
      template: match[3],
      source: fileName,
    });
  }
}

routes.sort((a, b) =>
  compareCodeUnits(a.template, b.template) ||
  compareCodeUnits(a.method, b.method) ||
  compareCodeUnits(a.source, b.source),
);

const keys = new Set();
for (const route of routes) {
  const key = `${route.method} ${route.template}`;
  if (keys.has(key)) throw new Error(`Duplicate API route registration: ${key}`);
  keys.add(key);
}

const rows = routes.map(
  (route) =>
    `  { method: ${JSON.stringify(route.method)}, template: ${JSON.stringify(route.template)}, source: ${JSON.stringify(route.source)} },`,
);
const generated = `// Generated by scripts/generate-api-route-manifest.mjs. Do not edit manually.\n` +
  `export const API_ROUTE_MANIFEST = [\n${rows.join("\n")}\n] as const;\n`;

if (process.argv.includes("--check")) {
  const current = readFileSync(outputPath, "utf8");
  if (current !== generated) {
    throw new Error("API route manifest is stale. Run pnpm codegen:api-route-manifest.");
  }
  console.log(`[route-manifest] ${routes.length} unique route registrations are current.`);
} else {
  mkdirSync(path.dirname(outputPath), { recursive: true });
  writeFileSync(outputPath, generated, "utf8");
  console.log(`[route-manifest] Wrote ${routes.length} unique routes to ${path.relative(repoRoot, outputPath)}.`);
}
